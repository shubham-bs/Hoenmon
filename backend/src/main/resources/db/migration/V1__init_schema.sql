CREATE TABLE smart_meter (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_number VARCHAR(64)  NOT NULL,
    name          VARCHAR(128) NOT NULL,
    manufacturer  VARCHAR(64),
    model         VARCHAR(64),
    phase_type    VARCHAR(16)  NOT NULL DEFAULT 'SINGLE_PHASE',
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_smart_meter_serial UNIQUE (serial_number)
);

CREATE TABLE meter_reading (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_id              BIGINT        NOT NULL,
    reading_timestamp     TIMESTAMPTZ   NOT NULL,
    active_power_kw       NUMERIC(10,4) NOT NULL,
    voltage               NUMERIC(7,3)  NOT NULL,
    current               NUMERIC(8,3)  NOT NULL,
    frequency             NUMERIC(6,3)  NOT NULL,
    power_factor          NUMERIC(5,4)  NOT NULL,
    cumulative_import_kwh NUMERIC(14,6) NOT NULL,
    cumulative_export_kwh NUMERIC(14,6) NOT NULL,
    source                VARCHAR(16)   NOT NULL DEFAULT 'SIMULATED',
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_meter_reading_meter
        FOREIGN KEY (meter_id) REFERENCES smart_meter (id) ON DELETE CASCADE,
    CONSTRAINT ck_meter_reading_voltage CHECK (voltage > 0),
    CONSTRAINT ck_meter_reading_current CHECK (current >= 0),
    CONSTRAINT ck_meter_reading_frequency CHECK (frequency > 0),
    CONSTRAINT ck_meter_reading_power_factor CHECK (power_factor >= -1 AND power_factor <= 1),
    CONSTRAINT ck_meter_reading_import CHECK (cumulative_import_kwh >= 0),
    CONSTRAINT ck_meter_reading_export CHECK (cumulative_export_kwh >= 0)
);

CREATE INDEX idx_meter_reading_meter_timestamp
    ON meter_reading (meter_id, reading_timestamp DESC);

CREATE INDEX idx_meter_reading_timestamp
    ON meter_reading (reading_timestamp DESC);
