package com.homeenergymonitor.ui.screens

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.homeenergymonitor.BuildConfig
import com.homeenergymonitor.domain.util.formatClockTime
import com.homeenergymonitor.ui.components.InfoRow
import com.homeenergymonitor.ui.components.SectionCard
import com.homeenergymonitor.ui.dashboard.DashboardUiState
import com.homeenergymonitor.ui.theme.TextSecondary

@Composable
fun DevicesScreen(
    state: DashboardUiState,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 16.dp, vertical = 12.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp)
    ) {
        SectionCard(
            title = "Smart meter",
            subtitle = "Single simulated three-state household meter"
        ) {
            InfoRow(
                "Serial",
                state.status?.meterId ?: state.latestReading?.meterId ?: "SIM-0001"
            )
            InfoRow("Source", state.status?.source ?: "SIMULATED")
            InfoRow("Connected", state.status?.connected?.let { if (it) "Yes" else "No" } ?: "--")
            InfoRow("State", state.status?.connectionState ?: "--")
            InfoRow(
                "Last reading",
                state.status?.lastReadingAt?.let { formatClockTime(it) } ?: "--"
            )
            InfoRow("Data", "DEMO DATA")
        }

        SectionCard(
            title = "Backend",
            subtitle = "Local Spring Boot telemetry service"
        ) {
            InfoRow("Base URL", BuildConfig.API_BASE_URL)
            InfoRow("REST", "/api/v1/meter/*")
            InfoRow("Live stream", "/api/v1/telemetry/stream (SSE)")
            InfoRow("Emulator host", "10.0.2.2 maps to this computer")
        }

        SectionCard(
            title = "About simulation",
            subtitle = "Version ${BuildConfig.VERSION_NAME}"
        ) {
            Text(
                text = "This build connects to a simulated single-phase meter. " +
                    "Power, voltage, current, frequency and energy are generated by the " +
                    "backend simulator and must not be treated as real measurements. " +
                    "Hardware integration is a later milestone.",
                color = TextSecondary,
                fontSize = 13.sp
            )
        }
    }
}
